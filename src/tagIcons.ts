export const DEFAULT_TAG_ICON = 'MapPin'

/** El ícono elegido, o uno genérico si no existe (por ejemplo, si se borró del set). */
export function resolveTagIcon(name: string | undefined): LucideIcon {
  return (name && ICON_OPTIONS[name]) || ICON_OPTIONS[DEFAULT_TAG_ICON]
}
